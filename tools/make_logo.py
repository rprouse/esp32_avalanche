#!/usr/bin/env python3
"""
Rasterize assets/icons/terrain.svg into an LVGL v9 A8 (alpha-only) image:
src/ui/logo_icon.c / logo_icon.h. The UI tints it with image_recolor.

Supports the simple SVG path subset the icon uses (M/L/H/V/C/Z, absolute and
relative); curves are flattened. The icon is mirrored horizontally so the lower
peak is on the right, cropped to its bounds and scaled to HEIGHT pixels.
Anti-aliasing uses SS x SS supersampling. Standard library only.

Usage:  python tools/make_logo.py [--preview out.png]
"""
import os
import re
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SVG = os.path.join(ROOT, "assets", "icons", "terrain.svg")
OUT_C = os.path.join(ROOT, "src", "ui", "logo_icon.c")
OUT_H = os.path.join(ROOT, "src", "ui", "logo_icon.h")
HEIGHT = 30
MIRROR = True
SS = 8


def parse_path(d):
    tokens = re.findall(r"[MmLlHhVvCcZz]|-?\d*\.?\d+(?:e-?\d+)?", d)
    pts, x, y, cmd, i = [], 0.0, 0.0, None, 0
    polys = []

    def num():
        nonlocal i
        v = float(tokens[i])
        i += 1
        return v

    while i < len(tokens):
        t = tokens[i]
        if re.match(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                if pts:
                    polys.append(pts)
                pts = []
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            if pts:
                polys.append(pts)
            pts = [(x, y)]
            cmd = "l" if rel else "L"  # implicit lineto after moveto
        elif c == "L":
            nx, ny = num(), num()
            x, y = (x + nx, y + ny) if rel else (nx, ny)
            pts.append((x, y))
        elif c == "H":
            nx = num()
            x = x + nx if rel else nx
            pts.append((x, y))
        elif c == "V":
            ny = num()
            y = y + ny if rel else ny
            pts.append((x, y))
        elif c == "C":
            p = [num() for _ in range(6)]
            if rel:
                p = [p[0] + x, p[1] + y, p[2] + x, p[3] + y, p[4] + x, p[5] + y]
            x0, y0 = x, y
            for k in range(1, 9):
                tt = k / 8
                a = (1 - tt) ** 3
                b = 3 * (1 - tt) ** 2 * tt
                cc = 3 * (1 - tt) * tt ** 2
                dd = tt ** 3
                pts.append((a * x0 + b * p[0] + cc * p[2] + dd * p[4], a * y0 + b * p[1] + cc * p[3] + dd * p[5]))
            x, y = p[4], p[5]
        else:
            raise ValueError(f"unsupported path command {cmd}")
    if pts:
        polys.append(pts)
    return polys


def inside(polys, px, py):
    # even-odd rule
    c = False
    for poly in polys:
        n = len(poly)
        for k in range(n):
            x1, y1 = poly[k]
            x2, y2 = poly[(k + 1) % n]
            if (y1 > py) != (y2 > py) and px < (x2 - x1) * (py - y1) / (y2 - y1) + x1:
                c = not c
    return c


def main():
    svg = open(SVG, encoding="utf-8").read()
    # The icon's shape is the path without fill="none".
    tags = re.findall(r"<path\s[^>]*>", svg)
    paths = [re.search(r'\sd="([^"]+)"', t).group(1) for t in tags if 'fill="none"' not in t]
    polys = [p for d in paths for p in parse_path(d)]
    xs = [x for p in polys for x, _ in p]
    ys = [y for p in polys for _, y in p]
    minx, maxx, miny, maxy = min(xs), max(xs), min(ys), max(ys)
    scale = HEIGHT / (maxy - miny)
    w = int(round((maxx - minx) * scale))
    h = HEIGHT

    alpha = bytearray()
    for py in range(h):
        for px in range(w):
            hits = 0
            for sy in range(SS):
                for sx in range(SS):
                    ux = (px + (sx + 0.5) / SS) / scale
                    uy = (py + (sy + 0.5) / SS) / scale + miny
                    gx = (maxx - ux) if MIRROR else (minx + ux)
                    if inside(polys, gx, uy):
                        hits += 1
            alpha.append(round(255 * hits / (SS * SS)))

    name = "logo_icon"
    c = ["/* Generated by tools/make_logo.py - do not edit. */",
         "/* Material Icons 'terrain' (c) Google, Apache 2.0 - see assets/icons/ */",
         '#include "logo_icon.h"', "",
         f"static const uint8_t {name}_map[] = {{"]
    for i in range(0, len(alpha), 24):
        c.append("    " + ",".join(f"0x{v:02x}" for v in alpha[i:i + 24]) + ",")
    c += ["};", "",
          f"const lv_image_dsc_t {name} = {{",
          "    .header.magic = LV_IMAGE_HEADER_MAGIC,",
          "    .header.cf = LV_COLOR_FORMAT_A8,",
          f"    .header.w = {w},",
          f"    .header.h = {h},",
          f"    .header.stride = {w},",
          f"    .data_size = sizeof({name}_map),",
          f"    .data = {name}_map,",
          "};", ""]
    with open(OUT_C, "w", newline="\n") as f:
        f.write("\n".join(c))
    with open(OUT_H, "w", newline="\n") as f:
        f.write("\n".join([
            "/* Generated by tools/make_logo.py - do not edit. */", "#pragma once", "",
            "#include <lvgl.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", "",
            f"/** Mountain logo, {w}x{h} A8 (alpha only): tint with image_recolor. */",
            f"extern const lv_image_dsc_t {name};", "",
            "#ifdef __cplusplus", "}", "#endif", ""]))
    print(f"wrote {OUT_C} ({w}x{h})")

    if "--preview" in sys.argv:
        out = sys.argv[sys.argv.index("--preview") + 1]
        bg = (0x1C, 0x26, 0x33)
        raw = b""
        for py in range(h):
            raw += b"\x00"
            for px in range(w):
                a = alpha[py * w + px] / 255
                raw += bytes(round(255 * a + bg[k] * (1 - a)) for k in range(3))

        def chunk(t, d):
            return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
        with open(out, "wb") as f:
            f.write(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                    + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
        print(f"preview: {out}")


if __name__ == "__main__":
    main()
