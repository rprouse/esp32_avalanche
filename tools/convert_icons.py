#!/usr/bin/env python3
"""
Convert the weather icon BMPs in assets/weather-icons/ into LVGL v9 image
descriptors (src/weather/weather_icons.c + .h).

The source icons are 24-bit BMPs drawn on black. To make them sit nicely on the
dark (non-black) UI, alpha is derived from brightness:
    a = max(r, g, b);  colour = rgb * 255 / a   (un-premultiplied)
Composited over black this reproduces the original exactly; over the dark navy
panels it blends smoothly with no black box.

Output format: LV_COLOR_FORMAT_RGB565A8 (RGB565 plane followed by an A8 plane).

Usage:  python tools/convert_icons.py      (no dependencies beyond the stdlib)
"""
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "weather-icons")
OUT_C = os.path.join(ROOT, "src", "weather", "weather_icons.c")
OUT_H = os.path.join(ROOT, "src", "weather", "weather_icons.h")
# (source folder, C name prefix, target size or None to keep the original size)
GROUPS = [("icon", "wi_large_", None), ("icon50", "wi_small_", None), ("icon", "wi_tiny_", 36),
          ("moon", "wi_moon_", None), ("wind", "wi_wind_", None)]


def read_bmp(path):
    with open(path, "rb") as f:
        b = f.read()
    if b[:2] != b"BM":
        raise ValueError(f"{path}: not a BMP")
    off, = struct.unpack_from("<I", b, 10)
    w, h = struct.unpack_from("<ii", b, 18)
    bpp, = struct.unpack_from("<H", b, 28)
    comp, = struct.unpack_from("<I", b, 30)
    if bpp != 24 or comp != 0:
        raise ValueError(f"{path}: need 24-bit uncompressed BMP (got {bpp} bpp, compression {comp})")
    row = (w * 3 + 3) // 4 * 4
    bottom_up = h > 0
    h = abs(h)
    px = []
    for y in range(h):
        sy = h - 1 - y if bottom_up else y
        r = b[off + sy * row: off + sy * row + w * 3]
        px.append([(r[i + 2], r[i + 1], r[i]) for i in range(0, w * 3, 3)])
    return w, h, px


def downscale(w, h, px, size):
    """Area-average resample to size x size. The source is effectively premultiplied
    (drawn on black), so averaging RGB directly is correct."""
    out = []
    sx, sy = w / size, h / size
    for ty in range(size):
        y0, y1 = ty * sy, (ty + 1) * sy
        row = []
        for tx in range(size):
            x0, x1 = tx * sx, (tx + 1) * sx
            acc = [0.0, 0.0, 0.0]
            area = 0.0
            for yy in range(int(y0), min(h, int(y1 + 0.9999))):
                wy = min(y1, yy + 1) - max(y0, yy)
                for xx in range(int(x0), min(w, int(x1 + 0.9999))):
                    wx = min(x1, xx + 1) - max(x0, xx)
                    a = wx * wy
                    if a <= 0:
                        continue
                    for k in range(3):
                        acc[k] += px[yy][xx][k] * a
                    area += a
            row.append(tuple(int(round(c / area)) for c in acc))
        out.append(row)
    return size, size, out


def to_rgb565a8(w, h, px):
    rgb = bytearray()
    alpha = bytearray()
    for y in range(h):
        for x in range(w):
            r, g, b = px[y][x]
            a = max(r, g, b)
            if a:
                r, g, b = (min(255, c * 255 // a) for c in (r, g, b))
            v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            rgb += struct.pack("<H", v)
            alpha.append(a)
    return bytes(rgb + alpha)


def ident(name):
    return re.sub(r"[^0-9a-zA-Z]", "_", name).lower()


def main():
    c = ['/* Generated by tools/convert_icons.py - do not edit. */',
         '/* Icons (c) Bodmer, FreeBSD license - see assets/weather-icons/LICENSE.txt */',
         '#include "weather_icons.h"', '']
    h = ['/* Generated by tools/convert_icons.py - do not edit. */', '#pragma once', '',
         '#include <lvgl.h>', '', '#ifdef __cplusplus', 'extern "C" {', '#endif', '']
    total = 0
    for folder, prefix, size in GROUPS:
        files = sorted(f for f in os.listdir(os.path.join(SRC, folder)) if f.lower().endswith(".bmp"))
        for f in files:
            w, hh, px = read_bmp(os.path.join(SRC, folder, f))
            if size:
                w, hh, px = downscale(w, hh, px, size)
            data = to_rgb565a8(w, hh, px)
            total += len(data)
            name = prefix + ident(os.path.splitext(f)[0])
            c.append(f"static const uint8_t {name}_map[] = {{")
            for i in range(0, len(data), 24):
                c.append("    " + ",".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
            c.append("};")
            c.append(f"const lv_image_dsc_t {name} = {{")
            c.append("    .header.magic = LV_IMAGE_HEADER_MAGIC,")
            c.append("    .header.cf = LV_COLOR_FORMAT_RGB565A8,")
            c.append(f"    .header.w = {w},")
            c.append(f"    .header.h = {hh},")
            c.append(f"    .header.stride = {w * 2},")
            c.append(f"    .data_size = sizeof({name}_map),")
            c.append(f"    .data = {name}_map,")
            c.append("};")
            c.append("")
            h.append(f"extern const lv_image_dsc_t {name};  /* {folder}/{f} {w}x{hh} */")
        h.append("")
    h += ['#ifdef __cplusplus', '}', '#endif', '']
    with open(OUT_C, "w", newline="\n") as fo:
        fo.write("\n".join(c))
    with open(OUT_H, "w", newline="\n") as fo:
        fo.write("\n".join(h))
    print(f"wrote {OUT_C} ({total / 1024:.0f} KB of image data) and {OUT_H}")


if __name__ == "__main__":
    sys.exit(main())
